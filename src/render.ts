import * as fs from 'node:fs';
import * as path from 'node:path';

/**
 * 渲染引擎：公共底座 base.md + 每家可选 overlay → 各家最终指令文件。
 * 产物写入 .config/build/<id>/<fileName>，链接目标一律指向产物，源文件永远只此一份。
 */

export interface RenderResult {
  id: string;
  file: string;
  bytes: number;
  overlayUsed: boolean;
}

export function baseMdPath(centerRoot: string): string {
  return path.join(centerRoot, 'AGENTS.md');
}

export function overlayPath(centerRoot: string, id: string): string {
  return path.join(centerRoot, 'overlays', `${id}.md`);
}

/** t 只需要 id 与最终文件名（来自 effectiveTarget，含用户覆盖后的路径）；frontmatter 供模块化规则目录使用 */
export function renderInstruction(
  centerRoot: string,
  t: { id: string; label?: string; instr: { fileName: string; frontmatter?: Record<string, string> } }
): RenderResult {
  const baseP = baseMdPath(centerRoot);
  if (!fs.existsSync(baseP)) {
    throw new Error(`缺少 ${baseP}，请先运行 agent-nexus init`);
  }
  const base = fs.readFileSync(baseP, 'utf8').trimEnd();
  const overlayP = overlayPath(centerRoot, t.id);
  const overlay = fs.existsSync(overlayP) ? fs.readFileSync(overlayP, 'utf8').trimEnd() : null;

  const outDir = path.join(centerRoot, '.config', 'build', t.id);
  fs.mkdirSync(outDir, { recursive: true });
  const outP = path.join(outDir, t.instr.fileName);

  const fm = t.instr.frontmatter
    ? '---\n' +
      Object.entries(t.instr.frontmatter)
        .map(([k, v]) => `${k}: ${JSON.stringify(v)}`)
        .join('\n') +
      '\n---\n\n'
    : '';
  const header = `<!-- Auto-generated by agent-nexus; do not edit directly.
     Edit AGENTS.md${overlay ? ` and overlays/${t.id}.md` : ''}, then run agent-nexus sync-agents -->`;
  let content = `${fm}${header}\n\n${base}`;
  if (overlay) content += `\n\n---\n\n${overlay}`;
  fs.writeFileSync(outP, content + '\n');

  return { id: t.id, file: outP, bytes: Buffer.byteLength(content), overlayUsed: !!overlay };
}
